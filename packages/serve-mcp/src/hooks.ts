/**
 * Claude Code hooks: one generated, dependency-free ES module that talks newline JSON-RPC to the
 * repository's daemon socket. It fails open (any error → exit 0, no output) so RIAF can never wedge a
 * session, and it never answers "allow" — that would bypass Claude Code's own permission prompts; it
 * only denies, to serve an answer from the index/cache, to ask for reflection, or to block a loop.
 *
 *   session-start  register the session
 *   prompt         route the prompt; inject the detailed agent prompt on the first prompt or when the reading changes
 *   pre            ask the governor (PreToolUse)
 *   post           record the result (PostToolUse)
 *   stop           end the session: utilisation, priors, skills (Stop)
 */

export interface HookScriptOptions {
  /** Absolute path of the riaf CLI, used to start the daemon when none is running. */
  cliPath?: string;
  /** Pins the pack budget for injected prompts (default: per intent from `.riaf/tokens.yaml`). */
  budget?: number;
}

export function hookScript(opts: HookScriptOptions = {}): string {
  return `#!/usr/bin/env node
// Generated by riaf (do not edit): Claude Code hooks for the RIAF daemon. Fails open.
import { connect } from 'node:net';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { join } from 'node:path';

const CLI = ${JSON.stringify(opts.cliPath ?? '')};
// Pack budget: per intent from .riaf/tokens.yaml unless RIAF_HOOK_BUDGET (or the generator) pins one.
const BUDGET = process.env.RIAF_HOOK_BUDGET ? Number(process.env.RIAF_HOOK_BUDGET) : ${opts.budget ?? 0};
const event = process.argv[2];
const done = (out) => { if (out) process.stdout.write(JSON.stringify(out)); process.exit(0); };

async function readStdin() {
  let s = '';
  for await (const c of process.stdin) s += c;
  return s ? JSON.parse(s) : {};
}

function rpc(socket, method, params, timeoutMs = 20000) {
  return new Promise((resolve, reject) => {
    const sock = connect(socket);
    let buf = '';
    const timer = setTimeout(() => { sock.destroy(); reject(new Error('timeout')); }, timeoutMs);
    sock.on('connect', () => sock.write(JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }) + '\\n'));
    sock.on('data', (d) => {
      buf += d;
      const nl = buf.indexOf('\\n');
      if (nl < 0) return;
      clearTimeout(timer);
      sock.end();
      const msg = JSON.parse(buf.slice(0, nl));
      msg.error ? reject(new Error(msg.error.message)) : resolve(msg.result);
    });
    sock.on('error', (e) => { clearTimeout(timer); reject(e); });
  });
}

async function daemonSocket(root) {
  const info = join(root, '.riaf', 'daemon.json');
  const read = () => { try { return JSON.parse(readFileSync(info, 'utf8')).socket; } catch { return undefined; } };
  let sock = read();
  if (sock) { try { await rpc(sock, 'daemon.info', {}, 2000); return sock; } catch { sock = undefined; } }
  if (!CLI || !existsSync(CLI)) return undefined;
  spawn(process.execPath, [CLI, 'serve', '--detached', '--root', root], { detached: true, stdio: 'ignore' }).unref();
  for (let i = 0; i < 30; i++) {
    await new Promise((r) => setTimeout(r, 100));
    sock = read();
    if (sock) { try { await rpc(sock, 'daemon.info', {}, 1000); return sock; } catch { /* starting */ } }
  }
  return undefined;
}

const deny = (reason) => ({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: reason } });

try {
  const input = await readStdin();
  const root = process.env.CLAUDE_PROJECT_DIR || input.cwd || process.cwd();
  const sessionId = input.session_id || 'claude-code';
  const socket = await daemonSocket(root);
  if (!socket) done();
  if (event === 'session-start') {
    await rpc(socket, 'govern.event', { sessionId, kind: 'session.start', payload: {} });
    done();
  }
  if (event === 'prompt') {
    const text = String(input.prompt ?? '').trim();
    if (!text || text.startsWith('/')) done();
    const stateDir = join(root, '.riaf', 'hooks-state');
    mkdirSync(stateDir, { recursive: true });
    const stateFile = join(stateDir, sessionId.replace(/[^\\w-]/g, '_') + '.json');
    const prev = existsSync(stateFile) ? JSON.parse(readFileSync(stateFile, 'utf8')) : undefined;
    const route = await rpc(socket, 'route', { text, ide: { interactive: true } });
    const top = Object.entries(route.w).sort((a, b) => b[1] - a[1])[0][0];
    if (prev && prev.top === top && route.branch !== 'clarify') {
      done({ hookSpecificOutput: { hookEventName: 'UserPromptSubmit', additionalContext: 'RIAF: same task (' + top + '); the pack from earlier in this session still applies — call riaf_pack for a fresh one if the focus moved.' } });
    }
    // The detailed agent prompt (protocol, task, plan, token budget, notes, pack, checks); older daemons get the pack.
    const pin = BUDGET > 0 ? { budget: BUDGET } : {};
    const r = await rpc(socket, 'prompt.build', { route, text, host: 'claude', sessionId, ...pin }, 60000)
      .then((b) => ({ pack: b.pack, rendered: b.prompt.text, promptId: b.prompt.promptId, tokens: b.prompt.plan.prompt }))
      .catch(() => rpc(socket, 'pack.compile', { route, target: 'claude', budget: BUDGET || 8000, sessionId }, 60000));
    await rpc(socket, 'govern.event', { sessionId, kind: 'session.start', payload: { request: text } });
    writeFileSync(stateFile, JSON.stringify({ top, packId: r.pack.packId, ...(r.promptId ? { promptId: r.promptId } : {}) }));
    if (r.promptId) {
      // keep the injected prompt so the RIAF console can show it next to what Claude Code did with it
      const promptsDir = join(root, '.riaf', 'prompts');
      mkdirSync(promptsDir, { recursive: true });
      const file = join(promptsDir, r.promptId + '.md');
      if (!existsSync(file)) writeFileSync(file, r.rendered);
      appendFileSync(join(promptsDir, 'index.jsonl'), JSON.stringify({ promptId: r.promptId, packId: r.pack.packId, task: text, host: 'claude', tokens: r.tokens, createdAt: new Date().toISOString(), source: 'hook', sessionId }) + '\\n');
    }
    done({ hookSpecificOutput: { hookEventName: 'UserPromptSubmit', additionalContext: r.rendered } });
  }
  if (event === 'pre') {
    const d = await rpc(socket, 'govern.toolCall', { sessionId, phase: 'explore', tool: input.tool_name, args: input.tool_input ?? {}, at: new Date().toISOString() }, 5000);
    if (d.kind === 'serve') done(deny(String(d.result)));
    if (d.kind === 'block') done(deny('RIAF governance: ' + d.reason));
    if (d.kind === 'reflect') done(deny('RIAF governance (a checkpoint, not an error): ' + d.message + ' Re-issue the call if you still need it.'));
    done();
  }
  if (event === 'post') {
    const res = input.tool_response;
    const text = typeof res === 'string' ? res : JSON.stringify(res ?? '');
    await rpc(socket, 'govern.event', { sessionId, kind: 'tool.result', payload: { tool: input.tool_name, args: input.tool_input ?? {}, result: text.slice(0, 60000) } }, 5000);
    done();
  }
  if (event === 'stop') {
    await rpc(socket, 'govern.event', { sessionId, kind: 'session.end', payload: {} }, 10000);
    done();
  }
  done();
} catch {
  done();
}
`;
}

/** The `hooks` block of `.claude/settings.json` (or a plugin's hooks.json) running `command <event>`. */
export function hooksConfig(command: string): Record<string, unknown> {
  const h = (event: string) => [{ type: 'command', command: `${command} ${event}`, timeout: event === 'prompt' ? 60 : 15 }];
  return {
    SessionStart: [{ hooks: h('session-start') }],
    UserPromptSubmit: [{ hooks: h('prompt') }],
    PreToolUse: [{ matcher: 'Grep|Glob|Read|Bash', hooks: h('pre') }],
    PostToolUse: [{ matcher: '*', hooks: h('post') }],
    Stop: [{ hooks: h('stop') }],
  };
}

/** Files of an installable Claude Code plugin bundling the MCP server, hooks and slash commands. */
export function pluginFiles(opts: { version: string; cliPath: string; commands: Record<string, string> }): Record<string, string> {
  const files: Record<string, string> = {
    '.claude-plugin/plugin.json': JSON.stringify({ name: 'riaf', version: opts.version, description: 'RIAF: budgeted, provenance-stamped context packs, repository navigation and tool-call governance for Claude Code.', author: { name: 'RIAF' } }, null, 2) + '\n',
    '.mcp.json': JSON.stringify({ mcpServers: { riaf: { type: 'stdio', command: process.execPath, args: [opts.cliPath, 'mcp'] } } }, null, 2) + '\n',
    'hooks/riaf-hook.mjs': hookScript({ cliPath: opts.cliPath }),
    'hooks/hooks.json': JSON.stringify({ hooks: hooksConfig('node "${CLAUDE_PLUGIN_ROOT}/hooks/riaf-hook.mjs"') }, null, 2) + '\n',
  };
  for (const [name, body] of Object.entries(opts.commands)) files[`commands/${name}`] = body;
  return files;
}
