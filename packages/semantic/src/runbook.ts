import type { Architecture } from './architecture.js';
import type { Convention } from './conventions.js';

/**
 * The operational run-book (a CLAUDE.md / AGENTS.md fragment): commands, layout, conventions and
 * hand-written constraints. Generated, and refuses to exceed 60 lines — an over-long run-book costs
 * every session tokens and gets ignored.
 */

export const RUNBOOK_MAX_LINES = 60;

export interface RunbookInput {
  repoName: string;
  architecture: Architecture;
  conventions: readonly Convention[];
  /** Hand-written constraints (e.g. `.riaf/constraints.md`), included verbatim and never trimmed. */
  constraints?: string;
}

/** Renders the run-book; throws when the hand-written part alone exceeds the limit. */
export function renderRunbook(input: RunbookInput): string {
  const a = input.architecture;
  const fixed: string[] = [];
  fixed.push(`# Run-book: ${input.repoName} (generated by RIAF — do not edit; edit .riaf/constraints.md)`, '');
  const cmds = Object.entries(a.commands).filter(([, v]) => v);
  if (cmds.length) {
    fixed.push('## Commands');
    for (const [k, v] of cmds) fixed.push(`- ${k}: \`${v}\``);
    fixed.push('');
  }
  const constraints = input.constraints?.trim();
  const tail = constraints ? ['', ...constraints.split('\n')] : [];
  const flexible: string[] = [];
  flexible.push('## Layout');
  const langs = Object.entries(a.languages).sort((x, y) => y[1] - x[1]).map(([l, n]) => `${l} ${n}`).join(', ');
  if (langs) flexible.push(`- languages: ${langs}${a.frameworks.length ? `; frameworks: ${a.frameworks.join(', ')}` : ''}`);
  const pk = a.packages.filter((p) => p.dir);
  if (pk.length) flexible.push(`- packages: ${pk.slice(0, 12).map((p) => `${p.dir} (${p.name})`).join(', ')}${pk.length > 12 ? ', …' : ''}`);
  if (a.entryPoints.length) flexible.push(`- entry points: ${a.entryPoints.slice(0, 6).join(', ')}`);
  for (const c of a.clusters.slice(0, 6)) flexible.push(`- ${c.name}/ (${c.files} files): ${c.sample.join(', ')}${c.files > c.sample.length ? ', …' : ''}`);
  if (a.testLayout.length) flexible.push(`- tests: ${a.testLayout.join(', ')}`);
  if (a.generated.length) flexible.push(`- generated (never edit): ${a.generated.join(', ')}`);
  const conv = input.conventions.filter((c) => c.confidence >= 0.8);
  if (conv.length) {
    flexible.push('', '## Conventions');
    for (const c of conv.slice(0, 12)) flexible.push(`- ${c.text}`);
  }
  const fixedLen = fixed.length + tail.length;
  if (fixedLen > RUNBOOK_MAX_LINES) throw new Error(`run-book: commands and constraints alone take ${fixedLen} lines (max ${RUNBOOK_MAX_LINES})`);
  const room = RUNBOOK_MAX_LINES - fixedLen;
  const body = flexible.length <= room ? flexible : flexible.slice(0, room);
  return [...fixed, ...body, ...tail].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}
